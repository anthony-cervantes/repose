package org.openrepose.valve

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.Paths
import java.util.concurrent.TimeUnit.SECONDS
import org.junit.runner.RunWith
import org.scalatest.funsuite.AnyFunSuite
import org.scalatestplus.junit.JUnitRunner

@RunWith(classOf[JUnitRunner])
class MainTest extends AnyFunSuite {
  test("the JVM entry point receives and handles command-line arguments") {
    val java = Paths.get(System.getProperty("java.home"), "bin", "java").toString
    val process = new ProcessBuilder(java, "-cp", System.getProperty("repose.main.classpath"),
      "org.openrepose.valve.Main", "--version").redirectErrorStream(true).start()
    try {
      assert(process.waitFor(20, SECONDS), "the version command did not terminate")
      val output = new String(process.getInputStream.readAllBytes(), UTF_8)
      assert(output.contains("Repose Valve:"), output)
      assert(process.exitValue() == 1, output)
    } finally process.destroyForcibly()
  }
}
